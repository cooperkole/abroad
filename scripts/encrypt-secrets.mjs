#!/usr/bin/env node
// Reads PHONE_E164 and FAMILY_PASSCODE from the gitignored .env.local and writes
// js/secrets.js, which holds only a salt, iteration count, verifier and the
// AES-GCM-encrypted phone number. Neither raw value is ever written to the repo.
//
// Usage: node scripts/encrypt-secrets.mjs
// Re-run whenever you change the passcode or phone number, then commit js/secrets.js.

import { readFileSync, writeFileSync } from 'node:fs';
import { webcrypto } from 'node:crypto';
import { deriveMaterial, encryptText, toB64, normalizePasscode } from '../js/crypto.js';

const ITERATIONS = 250_000;

export function readEnv(path = new URL('../.env.local', import.meta.url)) {
  let text;
  try {
    text = readFileSync(path, 'utf8');
  } catch {
    throw new Error('Missing .env.local. Create it with PHONE_E164=+1... and FAMILY_PASSCODE=... (see README).');
  }
  const env = {};
  for (const line of text.split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m) env[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }
  return env;
}

async function main() {
  const env = readEnv();
  const phone = env.PHONE_E164;
  const passcode = normalizePasscode(env.FAMILY_PASSCODE);
  if (!/^\+[1-9]\d{6,14}$/.test(phone ?? '')) throw new Error('PHONE_E164 must look like +15551234567');
  if (passcode.length < 4) throw new Error('FAMILY_PASSCODE must be at least 4 characters');

  const salt = toB64(webcrypto.getRandomValues(new Uint8Array(16)));
  const { keyB64, verifier } = await deriveMaterial(passcode, salt, ITERATIONS);
  const encrypted = await encryptText(keyB64, phone);

  const out = `// GENERATED by scripts/encrypt-secrets.mjs — do not edit by hand.
// Contains no plaintext: the phone number is AES-GCM encrypted under a key
// derived (PBKDF2-SHA256, ${ITERATIONS.toLocaleString('en-US')} iterations) from the family passcode.
export const SECRETS = ${JSON.stringify({ v: 1, salt, iterations: ITERATIONS, verifier, phone: encrypted }, null, 2)};
`;
  writeFileSync(new URL('../js/secrets.js', import.meta.url), out);
  console.log('Wrote js/secrets.js (encrypted). Commit it; never commit .env.local.');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main().catch((e) => {
    console.error(e.message);
    process.exit(1);
  });
}
